// Writes a SYNTHETIC order-flow CSV (see workload.hpp for the format).
// Usage: ob_gen [--ops N] [--prefill N] [--seed N] [--modify PCT] --out FILE

#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <string>

#include "orderbook/workload.hpp"

int main(int argc, char** argv) {
    ob::WorkloadParams p;
    std::string out;
    for (int i = 1; i + 1 < argc; i += 2) {
        const std::string k = argv[i];
        const char* v = argv[i + 1];
        if (k == "--ops") p.ops = std::strtoull(v, nullptr, 10);
        else if (k == "--prefill") p.prefill = std::strtoull(v, nullptr, 10);
        else if (k == "--seed") p.seed = std::strtoull(v, nullptr, 10);
        else if (k == "--modify") p.pctModify = static_cast<unsigned>(std::strtoul(v, nullptr, 10));
        else if (k == "--out") out = v;
        else {
            std::fprintf(stderr, "unknown option %s\n", k.c_str());
            return 2;
        }
    }
    if (out.empty()) {
        std::fprintf(stderr, "usage: ob_gen [--ops N] [--prefill N] [--seed N] [--modify PCT] --out FILE\n");
        return 2;
    }
    if (p.pctModify > 0) {  // take modifies out of the add/cancel share, keep 10% marketable
        p.pctAdd -= p.pctModify / 2 + p.pctModify % 2;
        p.pctCancel -= p.pctModify / 2;
    }
    const ob::Workload w = ob::generateWorkload(p);
    std::ofstream f(out);
    f << "# SYNTHETIC order flow generated by ob_gen (not real market data)\n";
    f << "# seed=" << p.seed << " prefill=" << p.prefill << " ops=" << p.ops << " add%=" << p.pctAdd
      << " cancel%=" << p.pctCancel << " modify%=" << p.pctModify << " ticks=" << p.numTicks << " mid=" << p.mid
      << "\n";
    f << "# A,id,side,price,qty | M,id,side,qty | X,id | R,id,price,qty\n";
    for (const auto& op : w.prefill) ob::writeCsv(f, op);
    for (const auto& op : w.ops) ob::writeCsv(f, op);
    std::printf("wrote %zu ops to %s (%zu limit, %zu cancel, %zu modify, %zu market, %zu marketable limit)\n",
                w.prefill.size() + w.ops.size(), out.c_str(), w.limitAdds + w.prefill.size(), w.cancels, w.modifies,
                w.markets, w.marketableLimits);
    return 0;
}
